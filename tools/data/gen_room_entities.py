"""Room v1 entities, DAOs, database and backup schema generated from the web's SQLAlchemy models
(the PoC 3 generator, now for :core:data). Read-only on the web project:

    cd <web>/backend && PYTHONDONTWRITEBYTECODE=1 PYTHONPATH=. .venv/bin/python \
        <JustStudyApp>/tools/data/gen_room_entities.py
"""

from pathlib import Path

from app.database.models import Base
from sqlalchemy import JSON, Boolean, DateTime, Float, Integer, String, Text

ROOT = Path(__file__).resolve().parents[2] / "core/data/src/main/java/com/dero/juststudykorean/data"
HEADER = "// Generated by tools/data/gen_room_entities.py from the web's models.py — do not edit."
SKIP = {"chunks_index"}  # Chroma's index: rebuilt on the phone
KINDS = [  # order matters: Boolean before Integer
    (Boolean, "BOOL", "Boolean"),
    (DateTime, "DATETIME", "Long"),
    (JSON, "JSON", "String"),
    (Float, "REAL", "Double"),
    (Integer, "INT", "Long"),
    (Text, "TEXT", "String"),
    (String, "TEXT", "String"),
]


# v2 (phase 4): notes_fts and processing_jobs (MIGRATION_1_2); v3: question_attempts(question_id) (MIGRATION_2_3);
# v5: Games' phone-only tables (MIGRATION_4_5, phase 8).
# v4: the web's index=True columns and flashcard_reviews(flashcard_id, reviewed_at) (MIGRATION_3_4). See R-002.
DB_VERSION = 5
SMALL = {"deck_places", "deck_groups", "custom_decks"}  # a handful of rows: no indices (R-002)
EXTRA_INDICES = {"question_attempts": [("question_id",)], "flashcard_reviews": [("flashcard_id", "reviewed_at")]}


def indices(t) -> list[tuple[str, ...]]:
    web = [] if t.name in SMALL else [(c.name,) for c in t.columns if c.index]
    return web + EXTRA_INDICES.get(t.name, [])
APP_TABLES = ["NotesFts", "ProcessingJobs", "GameSessions", "GameRounds", "GameItemProgress"]  # v5: Games (db/GameTables.kt)
APP_DAOS = ["Hot"]  # hand-written DAOs without a table of their own (db/HotDaos.kt)


def kind(column):
    for cls, k, kt in KINDS:
        if isinstance(column.type, cls):
            return k, kt
    raise SystemExit(f"unknown type {column.type!r} in {column.table.name}.{column.name}")


def camel(name: str, upper: bool = False) -> str:
    parts = name.split("_")
    head = parts[0].capitalize() if upper else parts[0]
    return head + "".join(p.capitalize() for p in parts[1:])


def main() -> None:
    tables = [t for t in Base.metadata.sorted_tables if t.name not in SKIP]
    entities = [HEADER, "package com.dero.juststudykorean.data.db", "",
                "import androidx.room3.ColumnInfo", "import androidx.room3.Entity", "import androidx.room3.Index", "",
                "// One entity per backup table, columns 1:1 with the web; dates as epoch millis (UTC); JSON as text.", ""]
    daos = [HEADER, "package com.dero.juststudykorean.data.db", "",
            "import androidx.room3.Dao", "import androidx.room3.Delete", "import androidx.room3.Insert",
            "import androidx.room3.Query", "import androidx.room3.Update", ""]
    schema = []
    for t in tables:
        name = camel(t.name, True)
        pks = [c.name for c in t.primary_key.columns]
        pk_list = ", ".join(f'"{p}"' for p in pks)
        order = ", ".join(pks)
        idx = ", ".join("Index(" + ", ".join(f'"{c}"' for c in cols) + ")" for cols in indices(t))
        idx = f", indices = [{idx}]" if idx else ""
        entities.append(f'@Entity(tableName = "{t.name}", primaryKeys = [{pk_list}]{idx})')
        entities.append(f"data class {name}Entity(")
        cols = []
        for c in t.columns:
            k, kt = kind(c)
            nullable = "?" if c.nullable and c.name not in pks else ""
            entities.append(f'    @ColumnInfo(name = "{c.name}") val {camel(c.name)}: {kt}{nullable},')
            cols.append(f'Col("{c.name}", Kind.{k})')
        entities += [")", ""]
        daos += ["@Dao", f"interface {name}Dao {{",
                 f'    @Query("SELECT * FROM {t.name} ORDER BY {order}")',
                 f"    suspend fun all(): List<{name}Entity>", "",
                 f'    @Query("SELECT COUNT(*) FROM {t.name}")',
                 "    suspend fun count(): Int", "",
                 f"    @Insert suspend fun insert(row: {name}Entity)",
                 f"    @Update suspend fun update(row: {name}Entity)",
                 f"    @Delete suspend fun delete(row: {name}Entity)", "}", ""]
        schema.append(f'    "{t.name}" to TableSpec(listOf({", ".join(cols)}), listOf({pk_list})),')

    db = [HEADER, "package com.dero.juststudykorean.data.db", "",
          "import androidx.room3.Database", "import androidx.room3.RoomDatabase", "",
          "@Database(", "    entities = ["]
    db += [f"        {camel(t.name, True)}Entity::class," for t in tables]
    # Phone-only tables (hand-written in db/AppTables.kt, never in the backup): v2 = the notes index and the pipeline.
    db += [f"        {name}Entity::class," for name in APP_TABLES]
    db += ["    ],", f"    version = {DB_VERSION},", "    exportSchema = true,", ")",
           "abstract class JustStudyDatabase : RoomDatabase() {"]
    db += [f"    abstract fun {camel(t.name)}Dao(): {camel(t.name, True)}Dao" for t in tables]
    db += [f"    abstract fun {name[0].lower() + name[1:]}Dao(): {name}Dao" for name in APP_TABLES + APP_DAOS]
    db += ["}", ""]

    spec = [HEADER, "package com.dero.juststudykorean.data.backup", "",
            "/** How each column is written in the backup's JSONL. */",
            "enum class Kind { INT, REAL, TEXT, BOOL, DATETIME, JSON }", "",
            "data class Col(val name: String, val kind: Kind)", "",
            "data class TableSpec(val columns: List<Col>, val primaryKey: List<String>)", "",
            "/** The 18 tables of `.jsbackup.zip` v1, in foreign-key order (SQLAlchemy sorted_tables). */",
            "val SCHEMA: LinkedHashMap<String, TableSpec> = linkedMapOf(", *schema, ")", ""]

    (ROOT / "db").mkdir(parents=True, exist_ok=True)
    (ROOT / "backup").mkdir(parents=True, exist_ok=True)
    (ROOT / "db/Entities.kt").write_text("\n".join(entities))
    (ROOT / "db/Daos.kt").write_text("\n".join(daos))
    (ROOT / "db/JustStudyDatabase.kt").write_text("\n".join(db))
    (ROOT / "backup/BackupSchema.kt").write_text("\n".join(spec))
    print(f"{len(tables)} tables")


if __name__ == "__main__":
    main()
