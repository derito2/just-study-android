"""PoC 3 (branch only): Room entities + column kinds generated from the web's SQLAlchemy models.

    PYTHONPATH=. .venv/bin/python <JustStudyApp>/tools/poc/gen_room_entities.py
"""

from pathlib import Path

from app.database.models import Base
from sqlalchemy import JSON, Boolean, DateTime, Float, Integer, String, Text

OUT = (
    Path(__file__).resolve().parents[2]
    / "app/src/androidTest/java/com/dero/juststudykorean/poc/room/PocEntities.kt"
)
SKIP = {"chunks_index"}
KINDS = [  # order matters: Boolean before Integer
    (Boolean, "BOOL", "Boolean"),
    (DateTime, "DATETIME", "Long"),
    (JSON, "JSON", "String"),
    (Float, "REAL", "Double"),
    (Integer, "INT", "Long"),
    (Text, "TEXT", "String"),
    (String, "TEXT", "String"),
]


def kind(column):
    for cls, k, kt in KINDS:
        if isinstance(column.type, cls):
            return k, kt
    raise SystemExit(f"unknown type {column.type!r} in {column.table.name}.{column.name}")


def camel(name: str, upper: bool = False) -> str:
    parts = name.split("_")
    head = parts[0].capitalize() if upper else parts[0]
    return head + "".join(p.capitalize() for p in parts[1:])


def main() -> None:
    tables = [t for t in Base.metadata.sorted_tables if t.name not in SKIP]
    out = [
        "// GENERATED by tools/poc/gen_room_entities.py from the web's models.py. PoC code.",
        "package com.dero.juststudykorean.poc.room",
        "",
        "import androidx.room3.ColumnInfo",
        "import androidx.room3.Entity",
        "",
    ]
    schema = []
    for t in tables:
        pks = [c.name for c in t.primary_key.columns]
        pk_list = ", ".join(f'"{p}"' for p in pks)
        out.append(f'@Entity(tableName = "{t.name}", primaryKeys = [{pk_list}])')
        out.append(f"data class {camel(t.name, True)}Row(")
        cols = []
        for c in t.columns:
            k, kt = kind(c)
            nullable = "?" if c.nullable and c.name not in pks else ""
            out.append(f'    @ColumnInfo(name = "{c.name}") val {camel(c.name)}: {kt}{nullable},')
            cols.append(f'Col("{c.name}", Kind.{k})')
        out.append(")")
        out.append("")
        schema.append(f'    "{t.name}" to TableSpec(listOf({", ".join(cols)}), listOf({pk_list})),')
    entities = ", ".join(f"{camel(t.name, True)}Row::class" for t in tables)
    out += [
        "enum class Kind { INT, REAL, TEXT, BOOL, DATETIME, JSON }",
        "",
        "data class Col(val name: String, val kind: Kind)",
        "",
        "data class TableSpec(val columns: List<Col>, val primaryKey: List<String>)",
        "",
        "/** Insertion order = foreign-key order (SQLAlchemy sorted_tables). */",
        "val SCHEMA: LinkedHashMap<String, TableSpec> = linkedMapOf(",
        *schema,
        ")",
        "",
        f"val ENTITIES = listOf({entities})",
        "",
    ]
    OUT.write_text("\n".join(out))
    print(f"{OUT.name}: {len(tables)} tables")


if __name__ == "__main__":
    main()
