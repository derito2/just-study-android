"""Writes app/src/main/java/com/dero/juststudykorean/ui/theme/{Tokens,JustStudyColors}.kt from design/tokens.json.

Run from the repo root after the design session updates the tokens:
    python3 tools/design/gen_tokens.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "app/src/main/java/com/dero/juststudykorean/ui/theme"
HEADER = "// Generated by tools/design/gen_tokens.py from design/tokens.json — do not edit.\npackage com.dero.juststudykorean.ui.theme\n\n"

tokens = json.loads((ROOT / "design/tokens.json").read_text())


def pascal(name):
    return "".join(p[:1].upper() + p[1:] for p in name.split("-"))


def camel(name):
    p = pascal(name)
    return p[:1].lower() + p[1:]


def argb(css):
    css = css.strip()
    if css.startswith("#"):
        assert len(css) == 7, css
        return f"0xFF{css[1:].upper()}"
    r, g, b, a = (x.strip() for x in re.match(r"rgba\(([^)]*)\)", css).group(1).split(","))
    return f"0x{round(float(a) * 255):02X}{int(r):02X}{int(g):02X}{int(b):02X}"


def px(value):
    assert value.endswith("px"), value
    return value[:-2]


colors = tokens["color"]["tokens"]
lines = [HEADER + "import androidx.compose.ui.graphics.Color\nimport androidx.compose.ui.unit.dp\nimport androidx.compose.ui.unit.sp\n\n"
         "/** Raw values of design/tokens.json. Screens use MaterialTheme / JustStudyTheme.colors, not these. */\nobject Tokens {"]
for t in colors:
    v = t["value"]
    if isinstance(v, dict):
        lines += [f"    val {pascal(t['name'])}Light = Color({argb(v['light'])})", f"    val {pascal(t['name'])}Dark = Color({argb(v['dark'])})"]
    else:
        lines.append(f"    val {pascal(t['name'])} = Color({argb(v)})")
lines.append("")
for group in ("spacing", "radius", "size"):
    for t in tokens[group]["tokens"]:
        lines.append(f"    val {pascal(t['name'])} = {px(t['value'])}.dp")
lines.append("")
for g in tokens["type"]["groups"]:
    for s in g["styles"]:
        ls = s.get("letterSpacing")
        em = f"{float(ls[:-2])}f" if ls else "0f"
        lines.append(f"    val {pascal(s['name'])} = TypeToken({px(s['fontSize'])}.sp, {s['lineHeight']}f, {s['fontWeight']}, letterSpacingEm = {em})")
lines.append("}\n\n/** One named text style of tokens.json: size, line height (multiplier), weight and tracking (em). */\n"
             "data class TypeToken(val size: androidx.compose.ui.unit.TextUnit, val lineHeight: Float, val weight: Int, val letterSpacingEm: Float)\n")
(OUT / "Tokens.kt").write_text("\n".join(lines))

fields, light, dark = [], [], []
for t in colors:
    n, v = t["name"], t["value"]
    fields.append(f"    val {camel(n)}: Color,")
    light.append(f"    {camel(n)} = Tokens.{pascal(n)}{'Light' if isinstance(v, dict) else ''},")
    dark.append(f"    {camel(n)} = Tokens.{pascal(n)}{'Dark' if isinstance(v, dict) else ''},")
(OUT / "JustStudyColors.kt").write_text(
    HEADER + "import androidx.compose.runtime.Immutable\nimport androidx.compose.runtime.staticCompositionLocalOf\nimport androidx.compose.ui.graphics.Color\n\n"
    "/** Every color token, for what ColorScheme does not have (go, fix, *-edge, *-pressed, streak-*...). */\n"
    "@Immutable\ndata class JustStudyColors(\n" + "\n".join(fields) + "\n)\n\n"
    "val LightJustStudyColors = JustStudyColors(\n" + "\n".join(light) + "\n)\n\n"
    "val DarkJustStudyColors = JustStudyColors(\n" + "\n".join(dark) + "\n)\n\n"
    "val LocalJustStudyColors = staticCompositionLocalOf { LightJustStudyColors }\n")
print(len(colors), "colors")
