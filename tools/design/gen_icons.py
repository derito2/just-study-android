"""Writes app/src/main/java/com/dero/juststudykorean/ui/components/LucidePaths.kt from design/icons/*.svg.

Every element (path, line, polyline, rect, circle) becomes one SVG path string, in order, so LucideIcon can
animate each part on its own. Run from the repo root: python3 tools/design/gen_icons.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUT = ROOT / "app/src/main/java/com/dero/juststudykorean/ui/components/LucidePaths.kt"
ICONS = ["layout-grid", "book-text", "layers", "circle-help", "graduation-cap", "menu", "languages",
         "trending-up", "calendar-days", "moon", "settings", "chevron-left", "badge-alert"]


def attrs(tag):
    return dict(re.findall(r'([\w-]+)="([^"]*)"', tag))


def to_path(tag):
    name = re.match(r"<(\w+)", tag).group(1)
    a = attrs(tag)
    f = lambda k, d="0": float(a.get(k, d))
    if name == "path":
        return a["d"]
    if name == "line":
        return f"M{f('x1')} {f('y1')}L{f('x2')} {f('y2')}"
    if name == "polyline":
        pts = a["points"].split()
        pairs = [f"{pts[i]} {pts[i + 1]}" for i in range(0, len(pts), 2)]
        return "M" + "L".join(pairs)
    if name == "rect":
        x, y, w, h, r = f("x"), f("y"), f("width"), f("height"), f("rx")
        return (f"M{x + r} {y}H{x + w - r}A{r} {r} 0 0 1 {x + w} {y + r}V{y + h - r}A{r} {r} 0 0 1 {x + w - r} {y + h}"
                f"H{x + r}A{r} {r} 0 0 1 {x} {y + h - r}V{y + r}A{r} {r} 0 0 1 {x + r} {y}Z")
    if name == "circle":
        cx, cy, r = f("cx"), f("cy"), f("r")
        if a.get("fill") == "currentColor" and a.get("stroke") == "none" and r == 1:
            return f"M{cx} {cy}h.01"  # filled 1-unit dot = a round-capped 2-unit stroke (same as Lucide's h.01 dots)
        return f"M{cx - r} {cy}A{r} {r} 0 1 0 {cx + r} {cy}A{r} {r} 0 1 0 {cx - r} {cy}Z"
    raise ValueError(name)


lines = ["// Generated by tools/design/gen_icons.py from design/icons — do not edit.",
         "package com.dero.juststudykorean.ui.components", "",
         "/** SVG path data of each part of a Lucide icon (24 × 24, stroke), in drawing order. */",
         "internal val Lucide.paths: List<String>", "    get() = when (this) {"]
for icon in ICONS:
    svg = re.sub(r"<metadata>.*?</metadata>", "", (ROOT / f"design/icons/{icon}.svg").read_text(), flags=re.S)
    parts = [to_path(t) for t in re.findall(r"<(?:path|line|polyline|rect|circle)\b[^>]*>", svg)]
    enum = "".join(w.capitalize() for w in icon.split("-"))
    lines.append(f"        Lucide.{enum} -> listOf(")
    lines += [f'            "{p}",' for p in parts]
    lines.append("        )")
lines += ["    }", ""]
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines))
print(OUT)
